import { useEffect, useState } from "react";
import { acknowledgeIncident, getIncident, summarizeIncident } from "../api";
import type { IncidentDetail, IncidentSummaryAIResponse } from "../types";

export function IncidentDetailPanel({ incidentId, onAcknowledged }: { incidentId: number; onAcknowledged: () => void }) {
  const [detail, setDetail] = useState<IncidentDetail | null>(null);
  const [summary, setSummary] = useState<IncidentSummaryAIResponse | null>(null);
  const [loadingSummary, setLoadingSummary] = useState(false);
  const [acking, setAcking] = useState(false);

  useEffect(() => {
    setDetail(null);
    setSummary(null);
    getIncident(incidentId).then(setDetail);
  }, [incidentId]);

  async function ack() {
    setAcking(true);
    try {
      await acknowledgeIncident(incidentId);
      const refreshed = await getIncident(incidentId);
      setDetail(refreshed);
      onAcknowledged();
    } finally {
      setAcking(false);
    }
  }

  async function loadSummary() {
    setLoadingSummary(true);
    try {
      setSummary(await summarizeIncident(incidentId));
    } finally {
      setLoadingSummary(false);
    }
  }

  if (!detail) return <div className="panel">Loading incident...</div>;

  return (
    <div className="panel">
      <div className="panel-header">
        <h2>
          Incident #{detail.id} <span className={`badge ${detail.severity === "critical" ? "critical" : "warn"}`}>{detail.severity}</span>
        </h2>
        {!detail.acknowledged_at && (
          <button onClick={ack} disabled={acking}>
            {acking ? "Acknowledging..." : "Acknowledge"}
          </button>
        )}
        {detail.acknowledged_at && (
          <span className="badge ack">
            ack'd by {detail.acknowledged_by} at {new Date(detail.acknowledged_at).toLocaleString()}
          </span>
        )}
      </div>

      <p>
        <strong>Signature:</strong> {detail.signature} &middot; <strong>Status:</strong> {detail.status} &middot;{" "}
        <strong>Services:</strong> {detail.affected_services.join(", ")}
      </p>
      <p className="muted">
        Opened {new Date(detail.opened_at).toLocaleString()}
        {detail.resolved_at && <> -- resolved {new Date(detail.resolved_at).toLocaleString()}</>}
      </p>

      <h3>Alerts</h3>
      <ul className="alert-list">
        {detail.alerts.map((a) => (
          <li key={a.id}>
            <strong>
              {a.service}/{a.metric_type}
            </strong>
            : {a.explanation}
          </li>
        ))}
      </ul>

      <h3>Evidence (linked trace events)</h3>
      <table className="evidence-table">
        <thead>
          <tr>
            <th>service</th>
            <th>event</th>
            <th>status</th>
            <th>duration</th>
            <th>trace</th>
          </tr>
        </thead>
        <tbody>
          {detail.evidence.map((e, i) => (
            <tr key={i}>
              <td>{e.service}</td>
              <td>{e.event_type}</td>
              <td>{e.status}</td>
              <td>{e.duration_ms.toFixed(1)}ms</td>
              <td className="mono">{e.trace_id.slice(0, 10)}...</td>
            </tr>
          ))}
          {detail.evidence.length === 0 && (
            <tr>
              <td colSpan={5} className="muted">
                No linked evidence found.
              </td>
            </tr>
          )}
        </tbody>
      </table>

      <h3>AI summary</h3>
      {!summary && (
        <button onClick={loadSummary} disabled={loadingSummary}>
          {loadingSummary ? "Summarizing..." : "Generate summary"}
        </button>
      )}
      {summary && (
        <div className="ai-summary">
          <div className="badge unknown">generated by: {summary.generated_by}</div>
          <p>{summary.summary}</p>
          <h4>Suspected cause (unverified inference)</h4>
          <p>{summary.suspected_cause}</p>
          <h4>Verified evidence</h4>
          <ul>
            {summary.verified_evidence.map((line, i) => (
              <li key={i} className="mono small">
                {line}
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}
